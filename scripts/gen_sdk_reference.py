#!/usr/bin/env python
"""Generate the Python SDK reference pages (fumadocs MDX) for the docs site.

The script introspects the installed ``leptonai`` package and writes:

- one page for ``leptonai.api.v2.APIClient`` (constructor, properties, errors),
- one page per resource group reachable from the client (``client.job`` ...),
- one page for the endpoint-calling ``leptonai.client.Client``,
- one page per module under ``leptonai.api.v2.types`` with a field table per
  pydantic model and a member table per enum,
- ``meta.json`` files so the pages show up in the sidebar.

Usage::

    python scripts/gen_sdk_reference.py --out <docs>/src/content/docs/reference/api

Existing ``index.mdx`` at the output root (the hand-written tutorial) is kept.
Pages previously produced by this script are replaced.
"""

