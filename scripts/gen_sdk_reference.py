# --------------------------------------------------------------------------- #
# Markdown / MDX helpers
# --------------------------------------------------------------------------- #

ROLE_RE = re.compile(
    r":(?:class|attr|mod|func|meth|obj|data|exc|ref|const|term):`~?([^`]+)`"
)
CODE_SPAN_RE = re.compile(r"(`[^`]*`)")
SECTION_RE = re.compile(
    r"^(Args|Arguments|Parameters|Returns|Return|Raises|Yields|Attributes|"
    r"Note|Notes|Usage|Example|Examples|Warning|Warnings|See Also):\s*$"
)
CODE_SECTIONS = {"Usage", "Example", "Examples"}


def escape_text(text: str) -> str:
    """Escape characters MDX would parse as JSX or expressions, outside code spans."""
    parts = CODE_SPAN_RE.split(text)
    for i in range(0, len(parts), 2):
        seg = parts[i]
        seg = seg.replace("{", "\\{").replace("}", "\\}").replace("<", "\\<")
        parts[i] = seg
    out = "".join(parts)
    if out.startswith("#"):
        out = "\\" + out
    return out


def inline_md(text: str) -> str:
    text = ROLE_RE.sub(lambda m: f"`{m.group(1)}`", text)
    text = text.replace("``", "`")
    return escape_text(text)


def cell(text: str) -> str:
    """Make text safe for a GFM table cell."""
    return inline_md(" ".join(text.split())).replace("|", "\\|")


def code(text: str) -> str:
    return "`" + text.replace("`", "'") + "`"


def own_doc(obj: Any) -> Optional[str]:
    """Docstring defined on the object itself, ignoring inherited ones."""
    if inspect.isclass(obj):
        doc = obj.__dict__.get("__doc__")
    else:
        doc = getattr(obj, "__doc__", None)
    if not doc or not doc.strip():
        return None
    return inspect.cleandoc(doc)


def first_line(doc: Optional[str]) -> str:
    if not doc:
        return ""
    para = doc.strip().split("\n\n", 1)[0]
    return " ".join(para.split())


def docstring_to_md(doc: Optional[str]) -> str:
    """Render a Google/RST-flavoured docstring as MDX-safe markdown."""
    if not doc:
        return ""
    lines = inspect.cleandoc(doc).splitlines()
    out: List[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        m = SECTION_RE.match(line.strip())
        if m and not line.startswith((" ", "\t")):
            name = m.group(1)
            block: List[str] = []
            i += 1
            while i < len(lines) and (
                lines[i].strip() == "" or lines[i].startswith((" ", "\t"))
            ):
                block.append(lines[i])
                i += 1
            while block and block[-1].strip() == "":
                block.pop()
            body = textwrap.dedent("\n".join(block))
            out.append("")
            out.append(f"**{name}:**")
            out.append("")
            if name in CODE_SECTIONS:
                out.extend(["```python", body, "```"])
            else:
                items: List[str] = []
                for bl in body.splitlines():
                    if not bl.strip():
                        continue
                    if bl.startswith((" ", "\t")) and items:
                        items[-1] += " " + bl.strip()
                    else:
                        items.append(bl.strip())
                out.extend("- " + inline_md(it) for it in items)
            out.append("")
            continue
        if line.startswith("    ") and line.strip():
            # RST-style literal block: indented lines outside a named section.
            block: List[str] = []
            while i < len(lines) and (
                lines[i].startswith("    ")
                or (
                    lines[i].strip() == ""
                    and i + 1 < len(lines)
                    and lines[i + 1].startswith("    ")
                )
            ):
                block.append(lines[i])
                i += 1
            code_text = textwrap.dedent("\n".join(block)).rstrip()
            out += ["", "```python", code_text, "```", ""]
            continue
        out.append(inline_md(line))
        i += 1
    text = "\n".join(out)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9_\- ]", "", name.lower()).replace(" ", "-")


def frontmatter(title: str, description: str) -> str:
    return (
        f"---\ntitle: {json.dumps(title)}\ndescription:"
        f" {json.dumps(' '.join(description.split()))}\n---\n\n{{/* {MARKER} from"
        f" leptonai {leptonai.__version__}. Do not edit by hand. */}}\n"
    )


