def resource_attrs() -> Dict[str, type]:
    """Map ``client.<attr>`` to the implementing class, from ``APIClient.__init__``."""
    src = inspect.getsource(APIClient.__init__)
    mapping: Dict[str, type] = {}
    for m in re.finditer(r"self\.(\w+)\s*=\s*(\w+)\(self\)", src):
        cls = getattr(client_module, m.group(2), None)
        if inspect.isclass(cls) and issubclass(cls, APIResourse):
            mapping[m.group(1)] = cls
    return mapping


def resource_pages(out: Path, route: str) -> List[Tuple[str, str]]:
    attrs = resource_attrs()
    public = [a for a in attrs if not a.startswith("_")]
    for attr in DISPATCHED:
        if attr not in public:
            public.append(attr)
    order = [a for a in PREFERRED_ORDER if a in public] + sorted(
        a for a in public if a not in PREFERRED_ORDER
    )

    pages: List[Tuple[str, str]] = []
    for attr in order:
        if attr in DISPATCHED:
            primary_attr, legacy_attr = DISPATCHED[attr]
            primary, legacy = attrs[primary_attr], attrs[legacy_attr]
        else:
            primary, legacy = attrs[attr], None

        prefix = f"client.{attr}"
        blurb = first_line(own_doc(primary)) or RESOURCE_BLURBS.get(
            attr, f"Operations exposed by {prefix}."
        )
        body = [frontmatter(prefix, blurb)]
        body.append(
            f"Accessed as {code(prefix)} on an [APIClient]({route}/client). "
            f"Implemented by {code(primary.__module__ + '.' + primary.__name__)}."
        )
        body.append("")
        if legacy is not None:
            prop = getattr(APIClient, attr)
            body.append(docstring_to_md(inspect.getdoc(prop.fget)))
            body.append("")
        class_doc = docstring_to_md(own_doc(primary))
        if class_doc:
            body += [class_doc, ""]

        primary_names = [n for n, _, _ in public_members(primary)]
        legacy_names = [n for n, _, _ in public_members(legacy)] if legacy else []
        only_primary = [
            n for n in primary_names if legacy is not None and n not in legacy_names
        ]
        only_legacy = [n for n in legacy_names if n not in primary_names]

        body += ["## Methods", "", summary_table(primary, primary_names), ""]
        if only_legacy:
            body += [
                f"Methods only available on the legacy {code(legacy.__name__)}: "
                + ", ".join(f"[{code(n)}](#{slug(n)})" for n in only_legacy)
                + ".",
                "",
            ]
        notes = {
            n: (
                "Only available when the workspace uses the new"
                f" {code(primary.__name__)}."
            )
            for n in only_primary
        }
        rendered, _ = render_members(primary, prefix, route, level=2, note_for=notes)
        body += [rendered, ""]
        if only_legacy:
            legacy_note = {
                n: (
                    f"Only available on the legacy {code(legacy.__name__)}, used when"
                    " the new API flag is off."
                )
                for n in only_legacy
            }
            rendered, _ = render_members(
                legacy, prefix, route, level=2, only=only_legacy, note_for=legacy_note
            )
            body += [rendered, ""]

        page_dir = out / attr
        page_dir.mkdir(parents=True, exist_ok=True)
        (page_dir / "index.mdx").write_text("\n".join(body).rstrip() + "\n")
        pages.append((attr, blurb))
    return pages


def client_page(out: Path, route: str, resources: List[Tuple[str, str]]) -> None:
    body = [
        frontmatter(
            "APIClient",
            "Entry point of the SDK: connects to a workspace and exposes one attribute"
            " per resource group.",
        )
    ]
    body += [
        "```python",
        "from leptonai.api.v2 import APIClient",
        "",
        (
            "client = APIClient()  # workspace from `lep login` or LEPTON_WORKSPACE_*"
            " env vars"
        ),
        'client = APIClient(workspace_id="my-workspace", auth_token="...")',
        "```",
        "",
        docstring_to_md(own_doc(APIClient)),
        "",
        "## Constructor",
        "",
        render_callable(None, "APIClient", APIClient.__init__, route),
        "## Resource groups",
        "",
        "| Attribute | Description |",
        "|-----------|-------------|",
    ]
    for attr, blurb in resources:
        body.append(f"| [{code('client.' + attr)}]({route}/{attr}) | {cell(blurb)} |")
    body.append("")

    members = public_members(APIClient)
    props = [(n, fn) for n, fn, kind in members if kind == "property"]
    methods = [(n, fn, kind) for n, fn, kind in members if kind != "property"]
    if props:
        body += ["## Properties", ""]
        for name, fn in props:
            body += [render_property(name, fn, route, level=3), ""]
    if methods:
        body += ["## Methods", ""]
        for name, fn, kind in methods:
            body += [
                render_callable(
                    name,
                    f"client.{name}",
                    fn,
                    route,
                    level=3,
                    skip_first=kind != "staticmethod",
                ),
                "",
            ]

    funcs = [
        (n, obj)
        for n in getattr(api_v2, "__all__", [])
        for obj in [getattr(api_v2, n, None)]
        if inspect.isfunction(obj)
    ]
    if funcs:
        body += ["## Module functions", ""]
        for name, fn in funcs:
            body += [
                render_callable(
                    name,
                    f"leptonai.api.v2.{name}",
                    fn,
                    route,
                    level=3,
                    skip_first=False,
                ),
                "",
            ]

    errors = [
        (n, obj)
        for n in getattr(api_v2, "__all__", [])
        for obj in [getattr(api_v2, n, None)]
        if inspect.isclass(obj) and issubclass(obj, BaseException)
    ]
    if errors:
        body += [
            "## Errors",
            "",
            "All of these are importable from {}.".format(code("leptonai.api.v2")),
            "",
            "| Error | Base | Description |",
            "|-------|------|-------------|",
        ]
        for name, cls in errors:
            base = cls.__bases__[0].__name__
            body.append(
                f"| {code(name)} | {code(base)} | {cell(first_line(own_doc(cls)))} |"
            )
        body.append("")

    body += [
        "## WorkspaceRecord",
        "",
        (
            f"Importable as {code('leptonai.api.v2.WorkspaceRecord')}. Manages the"
            f" workspaces saved locally by {code('lep login')}."
        ),
        "",
        docstring_to_md(own_doc(WorkspaceRecord)),
        "",
    ]
    rendered, _ = render_members(WorkspaceRecord, "WorkspaceRecord", route, level=3)
    body += [rendered, ""]

    page_dir = out / "client"
    page_dir.mkdir(parents=True, exist_ok=True)
    (page_dir / "index.mdx").write_text("\n".join(body).rstrip() + "\n")


