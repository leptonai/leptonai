def resolve_hints(fn: Any) -> Dict[str, Any]:
    try:
        return typing.get_type_hints(fn)
    except Exception:
        return dict(getattr(fn, "__annotations__", {}) or {})


def build_signature(
    prefix: str, fn: Any, skip_first: bool
) -> Tuple[str, List[Tuple[str, Any, Any]], Any]:
    """Return (signature text, [(name, annotation, default)], return annotation)."""
    sig = inspect.signature(fn)
    hints = resolve_hints(fn)
    params: List[str] = []
    details: List[Tuple[str, Any, Any]] = []
    items = list(sig.parameters.items())
    if skip_first and items and items[0][0] in ("self", "cls"):
        items = items[1:]
    seen_star = False
    for name, p in items:
        if p.kind == p.KEYWORD_ONLY and not seen_star:
            params.append("*")
            seen_star = True
        ann = hints.get(name, p.annotation)
        text = name
        if p.kind == p.VAR_POSITIONAL:
            text = "*" + name
            seen_star = True
        elif p.kind == p.VAR_KEYWORD:
            text = "**" + name
        if ann is not inspect.Parameter.empty:
            text += f": {fmt_type(ann)}"
        if p.default is not inspect.Parameter.empty:
            sep = " = " if ann is not inspect.Parameter.empty else "="
            text += sep + fmt_default(p.default)
        params.append(text)
        details.append((name, ann, p.default))
    ret = hints.get("return", sig.return_annotation)
    ret_text = f" -> {fmt_type(ret)}" if ret is not inspect.Signature.empty else ""
    one_line = f"{prefix}({', '.join(params)}){ret_text}"
    if len(one_line) <= 88:
        return one_line, details, ret
    inner = "".join(f"\n    {p}," for p in params)
    return f"{prefix}({inner}\n){ret_text}", details, ret


def is_deprecated(fn: Any) -> bool:
    try:
        return "DeprecationWarning" in inspect.getsource(fn)
    except (OSError, TypeError):
        return False


def render_callable(
    heading: Optional[str],
    prefix: str,
    fn: Any,
    route: str,
    level: int = 2,
    skip_first: bool = True,
    note: Optional[str] = None,
) -> str:
    sig, details, ret = build_signature(prefix, fn, skip_first)
    out = [f"{'#' * level} {heading}", ""] if heading else []
    if is_deprecated(fn):
        out += [
            (
                "> **Deprecated.** This method emits a `DeprecationWarning`; see the"
                " description below."
            ),
            "",
        ]
    if note:
        out += [f"> {note}", ""]
    out += ["```python", sig, "```", ""]
    doc = docstring_to_md(inspect.getdoc(fn))
    if doc:
        out += [doc, ""]
    if details:
        out += ["**Parameters**", ""]
        for name, ann, default in details:
            line = f"- {code(name)}"
            if ann is not inspect.Parameter.empty:
                line += f": {typed(ann, route)}"
            if default is not inspect.Parameter.empty:
                line += f", default {code(fmt_default(default))}"
            out.append(line)
        out.append("")
    if ret is not inspect.Signature.empty and ret is not None and ret is not NoneType:
        out += [f"**Returns** {typed(ret, route)}", ""]
    return "\n".join(out)


def public_members(cls: type) -> List[Tuple[str, Any, str]]:
    """(name, unwrapped callable, kind) for public members defined on ``cls`` itself, in source order."""
    members: List[Tuple[int, str, Any, str]] = []
    for name, raw in cls.__dict__.items():
        if name.startswith("_"):
            continue
        if isinstance(raw, property):
            fn, kind = raw.fget, "property"
        elif isinstance(raw, (staticmethod, classmethod)):
            fn, kind = raw.__func__, type(raw).__name__
        elif inspect.isfunction(raw):
            fn, kind = raw, "method"
        else:
            continue
        if fn is None:
            continue
        try:
            line = inspect.getsourcelines(fn)[1]
        except (OSError, TypeError):
            line = 10**9
        members.append((line, name, fn, kind))
    members.sort(key=lambda m: m[0])
    return [(name, fn, kind) for _, name, fn, kind in members]


def render_property(heading: str, fn: Any, route: str, level: int = 2) -> str:
    hints = resolve_hints(fn)
    ret = hints.get("return", inspect.signature(fn).return_annotation)
    out = [f"{'#' * level} {heading}", ""]
    if ret is not inspect.Signature.empty:
        out += [f"Property of type {typed(ret, route)}.", ""]
    else:
        out += ["Property.", ""]
    doc = docstring_to_md(inspect.getdoc(fn))
    if doc:
        out += [doc, ""]
    return "\n".join(out)


def render_members(
    cls: type,
    prefix: str,
    route: str,
    level: int = 2,
    only: Optional[Iterable[str]] = None,
    note_for: Optional[Dict[str, str]] = None,
) -> Tuple[str, List[str]]:
    """Render all public members of a class. Returns (markdown, method names)."""
    chunks: List[str] = []
    names: List[str] = []
    wanted = set(only) if only is not None else None
    for name, fn, kind in public_members(cls):
        if wanted is not None and name not in wanted:
            continue
        names.append(name)
        if kind == "property":
            chunks.append(render_property(f"{name}", fn, route, level))
        else:
            skip_first = kind != "staticmethod"
            chunks.append(
                render_callable(
                    name,
                    f"{prefix}.{name}",
                    fn,
                    route,
                    level,
                    skip_first=skip_first,
                    note=(note_for or {}).get(name),
                )
            )
    return "\n".join(chunks), names


def summary_table(cls: type, names: Iterable[str]) -> str:
    rows = ["| Method | Description |", "|--------|-------------|"]
    for name in names:
        raw = cls.__dict__.get(name)
        fn = getattr(raw, "fget", None) or getattr(raw, "__func__", None) or raw
        rows.append(
            f"| [{code(name)}](#{slug(name)}) |"
            f" {cell(first_line(inspect.getdoc(fn)))} |"
        )
    return "\n".join(rows)


