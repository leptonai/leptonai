def is_sdk_type(obj: Any) -> bool:
    return (
        inspect.isclass(obj)
        and obj.__module__.startswith("leptonai.api.v2.types")
        and (issubclass(obj, BaseModel) or issubclass(obj, enum.Enum))
    )


def type_link(cls: type, route: str) -> str:
    module = cls.__module__.rsplit(".", 1)[-1]
    return f"{route}/types/{module}#{slug(cls.__name__)}"


def fmt_type(tp: Any, refs: Optional[Set[type]] = None) -> str:
    if refs is None:
        refs = set()
    if tp is inspect.Parameter.empty or tp is inspect.Signature.empty:
        return ""
    if tp is None or tp is NoneType:
        return "None"
    if tp is Ellipsis:
        return "..."
    if isinstance(tp, str):
        return tp
    if isinstance(tp, list):
        return "[" + ", ".join(fmt_type(a, refs) for a in tp) + "]"
    if isinstance(tp, typing.ForwardRef):
        return tp.__forward_arg__
    if isinstance(tp, typing.TypeVar):
        return tp.__name__
    if tp is typing.Any:
        return "Any"
    origin = typing.get_origin(tp)
    args = typing.get_args(tp)
    if origin is typing.Union or origin is getattr(pytypes, "UnionType", None):
        non_none = [a for a in args if a is not NoneType]
        if len(args) == 2 and len(non_none) == 1:
            return f"Optional[{fmt_type(non_none[0], refs)}]"
        return "Union[" + ", ".join(fmt_type(a, refs) for a in args) + "]"
    if origin is typing.Literal:
        return "Literal[" + ", ".join(repr(a) for a in args) + "]"
    if origin is not None:
        name = getattr(origin, "__name__", None) or str(origin)
        name = {
            "list": "List",
            "dict": "Dict",
            "set": "Set",
            "frozenset": "FrozenSet",
            "tuple": "Tuple",
            "type": "Type",
        }.get(name, name)
        if not args:
            return name
        return f"{name}[" + ", ".join(fmt_type(a, refs) for a in args) + "]"
    if inspect.isclass(tp):
        if is_sdk_type(tp):
            refs.add(tp)
        return tp.__name__
    return repr(tp).replace("typing.", "")


def fmt_default(value: Any) -> str:
    if isinstance(value, enum.Enum):
        return f"{type(value).__name__}.{value.name}"
    if isinstance(value, BaseModel):
        return f"{type(value).__name__}(...)"
    if inspect.isclass(value) or inspect.isfunction(value):
        return value.__name__
    text = repr(value)
    if len(text) > 48:
        text = text[:45] + "..."
    return text


def typed(tp: Any, route: str) -> str:
    """Inline-code type plus links to SDK types it references."""
    refs: Set[type] = set()
    text = fmt_type(tp, refs)
    if not text:
        return ""
    if len(refs) == 1:
        cls = next(iter(refs))
        return f"[{code(text)}]({type_link(cls, route)})"
    out = code(text)
    if refs:
        links = ", ".join(
            f"[{c.__name__}]({type_link(c, route)})"
            for c in sorted(refs, key=lambda c: c.__name__)
        )
        out += f" (see {links})"
    return out


